function renderPhaseTargets() {
  const table = phases
    .map(
      (phase) =>
        `| ${phase.window} | ${phase.name} | ${phase.buds} | ${phase.bps} | ${phase.bpc} | ${phase.items} | ${phase.upgrades} | ${phase.research} | ${phase.events} | ${phase.seeds} | ${phase.prestige} | ${phase.activeShare} |`,
    )
    .join('\n');

  return `# Phase Targets: 2-20 Hour Release Curve

Generated by \`npm run balance:simulate\`.

| Window | Phase | Target Buds | Target BPS | Target BPC | Items | Upgrades | Research | Events | Seeds | Prestige | Active Share |
| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
${table}

## Balance Intent

- The first prestige should become visible around 60-90 minutes, but the first efficient prestige should usually happen after the player has seen research and multiple upgrade categories.
- Active clicking remains relevant through BPC, event catch-up, abilities, and achievement score, but idle production becomes the dominant long-run driver after several prestiges.
- Events are tuned as acceleration windows, not mandatory progression. A semi-idle profile remains within one major phase of an active profile.
- Offline gain uses persisted non-temporary BPS and a capped payout, so closing the tab during a short boost does not multiply the return window.
`;
}

function renderSimulationResults() {
  const table = rows
    .map(
      (row) =>
        `| ${row.profile} | ${row.minutes} | ${format(row.buds)} | ${format(row.bps)} | ${row.events} | ${row.seeds} | ${row.research} | ${row.prestigeCount} |`,
    )
    .join('\n');

  return `# Heuristic Balance Simulation Results

Generated by \`npm run balance:simulate\`. This is a lightweight release-owner pass, not a test suite.

| Profile | Minutes | Buds | BPS | Events | Seeds | Research | Prestiges |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
${table}

## Exploit Pass

| Risk | Release Decision |
| --- | --- |
| Offline gain during temporary BPS buffs | Persisted offline BPS strips event, ability and kickstart multipliers before save. |
| Event-seed spikes | Seed-heavy events are late-weighted and pity-controlled; rare events add excitement without replacing prestige. |
| Buy Max during cost buffs | Temporary cost multipliers are visible as active buffs; value is intentional but duration-limited. |
| Save import corruption | Import initializes and validates before overwriting storage. Invalid saves never replace the current save. |
| Achievement multiplier runaway | Achievement score bonus is capped at +6%, with only major achievements carrying extra tiny multipliers. |
| Early event skip | Event gating and category pity prevent the first two minutes from being decided by a single rare spawn. |

## Manual Playthrough Notes

- 30 minutes without prestige: first item, first upgrade, several item milestones, early events, and first research hints should all appear without a hard stop.
- First prestige run: target is 60-110 minutes depending on event engagement and active clicking. Prestige before the first research branch should be visibly inefficient.
- Second run: target speedup is roughly 1.6x-2.4x through prestige multiplier, early research, and stronger event handling.
- 4 hour run: player should be in repeated prestige planning with 25-40 research nodes and most shop identities understood.
- 10 hour run: late research, achievement score, cosmetics, and event specialization become the main motivators.
`;
}

function format(value) {
  if (value >= 1_000_000_000_000) {
    return `${(value / 1_000_000_000_000).toFixed(2)}T`;
  }
  if (value >= 1_000_000_000) {
    return `${(value / 1_000_000_000).toFixed(2)}B`;
  }
  if (value >= 1_000_000) {
    return `${(value / 1_000_000).toFixed(2)}M`;
  }
  if (value >= 1_000) {
    return `${(value / 1_000).toFixed(1)}k`;
  }
  return String(value);
}
