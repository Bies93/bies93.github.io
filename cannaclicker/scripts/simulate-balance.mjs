    const idleFactor = 1 + profile.idleRatio * 0.22;
    const prestigeFactor = Math.pow(profile.prestigeBias, Math.max(0, Math.log2(minutes / 60)));
    const runScore = activeFactor * eventFactor * idleFactor * prestigeFactor;
    const prestigeCount = Math.max(0, Math.floor((minutes - 78) / 92 * profile.prestigeBias));
    const seeds = Math.max(0, Math.floor(Math.pow(minutes / 40, 1.42) * 2.8 * profile.prestigeBias));
